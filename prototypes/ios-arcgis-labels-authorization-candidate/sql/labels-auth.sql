CREATE ROLE labels_auth_verifier NOLOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION;
CREATE SCHEMA labels_auth AUTHORIZATION postgres;
REVOKE ALL ON SCHEMA labels_auth FROM PUBLIC,anon,authenticated,service_role;
CREATE TABLE labels_auth.challenges (
 id uuid PRIMARY KEY CHECK(id::text ~ '^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$'),
 purpose text NOT NULL DEFAULT 'gridly-labels-lease-v1' CHECK(purpose='gridly-labels-lease-v1'),
 key_hash text NOT NULL REFERENCES subscription_ops.apple_app_attest_keys(key_hash),
 app_id text NOT NULL DEFAULT '2XSH6R7K37.com.gridlygo.gridly' CHECK(app_id='2XSH6R7K37.com.gridlygo.gridly'),
 store_environment text NOT NULL DEFAULT 'sandbox' CHECK(store_environment='sandbox'),
 attest_environment text NOT NULL DEFAULT 'production' CHECK(attest_environment='production'),
 tile_fingerprint text NOT NULL CHECK(tile_fingerprint ~ '^[A-Za-z0-9_-]{43}$'),
 paid_digest text NOT NULL CHECK(paid_digest ~ '^[A-Za-z0-9_-]{43}$'),
 binding text NOT NULL CHECK(binding ~ '^[A-Za-z0-9_-]{43}$'),
 gateway_id text NOT NULL DEFAULT 'gridly-labels-consumer-pilot-v1' CHECK(gateway_id='gridly-labels-consumer-pilot-v1'),
 created_at timestamptz NOT NULL,
 expires_at timestamptz NOT NULL,
 consumed_at timestamptz,
