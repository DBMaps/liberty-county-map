REVOKE ALL ON labels_auth.challenges FROM PUBLIC,anon,authenticated,service_role,labels_auth_verifier;

-- p_id is generated by the trusted gateway, never selected in a client body.
-- paid_digest binds bytes; it is NOT an ownership verdict. Apple verifies those bytes before a lease.
CREATE FUNCTION labels_auth.issue_challenge(p_id uuid,p_key_hash text,p_tile_fingerprint text,p_paid_digest text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path='' SET lock_timeout='750ms' AS $$
DECLARE t timestamptz;b text;
BEGIN
 IF p_id IS NULL OR p_id::text !~ '^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$'
 OR p_key_hash IS NULL OR p_key_hash !~ '^[a-f0-9]{64}$'
 OR p_tile_fingerprint IS NULL OR p_tile_fingerprint !~ '^[A-Za-z0-9_-]{43}$'
 OR p_paid_digest IS NULL OR p_paid_digest !~ '^[A-Za-z0-9_-]{43}$' THEN RETURN NULL; END IF;
 IF NOT EXISTS(SELECT FROM subscription_ops.apple_app_attest_keys WHERE key_hash=p_key_hash AND environment='production') THEN RETURN NULL; END IF;
 PERFORM pg_catalog.pg_advisory_xact_lock(24466,4);
 t:=pg_catalog.clock_timestamp();
 DELETE FROM labels_auth.challenges WHERE id IN
 (SELECT id FROM labels_auth.challenges WHERE expires_at<=t ORDER BY expires_at LIMIT 500);
 IF (SELECT count(*) FROM labels_auth.challenges)>=1024 OR
 (SELECT count(*) FROM labels_auth.challenges WHERE key_hash=p_key_hash AND consumed_at IS NULL)>=16 THEN RETURN NULL; END IF;
 b:=pg_catalog.rtrim(pg_catalog.translate(pg_catalog.encode(pg_catalog.sha256(pg_catalog.convert_to(
 pg_catalog.array_to_json(ARRAY['gridly-labels-lease-v1','com.gridlygo.gridly','sandbox','production',p_id::text,p_paid_digest,p_tile_fingerprint])::text,'UTF8')),'base64'),'+/','-_'),'=');
 INSERT INTO labels_auth.challenges(id,key_hash,tile_fingerprint,paid_digest,binding,created_at,expires_at)
 VALUES(p_id,p_key_hash,p_tile_fingerprint,p_paid_digest,b,t,t+interval '2 minutes') ON CONFLICT DO NOTHING;
 IF NOT FOUND THEN RETURN NULL; END IF;
 RETURN pg_catalog.jsonb_build_object('challengeId',p_id,'expiresAt',floor(extract(epoch FROM t+interval '2 minutes')*1000)::bigint,
 'purpose','gridly-labels-lease-v1');
END $$;

CREATE FUNCTION labels_auth.read_challenge(p_id uuid) RETURNS jsonb
LANGUAGE sql VOLATILE SECURITY DEFINER SET search_path='' SET lock_timeout='750ms' AS $$
 SELECT pg_catalog.jsonb_build_object('challengeId',c.id,'purpose',c.purpose,'keyHash',c.key_hash,
 'appId',c.app_id,'store',c.store_environment,'attest',c.attest_environment,'fingerprint',c.tile_fingerprint,
 'paidDigest',c.paid_digest,'binding',c.binding,'gatewayId',c.gateway_id,
 'expiresAt',floor(extract(epoch FROM c.expires_at)*1000)::bigint,
 'publicSpki',k.public_spki,'counter',k.assertion_counter,'environment',k.environment)
 FROM labels_auth.challenges c JOIN subscription_ops.apple_app_attest_keys k ON k.key_hash=c.key_hash
 WHERE c.id=p_id AND c.consumed_at IS NULL AND c.expires_at>pg_catalog.clock_timestamp() AND k.environment='production'
$$;

CREATE FUNCTION labels_auth.consume_challenge(p_id uuid,p_key_hash text,p_binding text,p_counter bigint)
RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER SET search_path='' SET lock_timeout='750ms' AS $$
DECLARE c labels_auth.challenges;k subscription_ops.apple_app_attest_keys;t timestamptz;n integer;
BEGIN
 IF p_id IS NULL OR p_key_hash IS NULL OR p_key_hash !~ '^[a-f0-9]{64}$'
 OR p_binding IS NULL OR p_binding !~ '^[A-Za-z0-9_-]{43}$'
 OR p_counter IS NULL OR p_counter<1 OR p_counter>4294967295 THEN RETURN false; END IF;
 -- Same order as subscription consumption: own challenge, then shared key row.
 SELECT * INTO c FROM labels_auth.challenges WHERE id=p_id FOR UPDATE;
 IF NOT FOUND OR c.consumed_at IS NOT NULL OR c.key_hash<>p_key_hash OR c.binding<>p_binding
 OR c.purpose<>'gridly-labels-lease-v1' OR c.app_id<>'2XSH6R7K37.com.gridlygo.gridly'
 OR c.store_environment<>'sandbox' OR c.attest_environment<>'production'
 OR c.gateway_id<>'gridly-labels-consumer-pilot-v1' THEN RETURN false; END IF;
 SELECT * INTO k FROM subscription_ops.apple_app_attest_keys WHERE key_hash=c.key_hash FOR UPDATE;
 IF NOT FOUND THEN RETURN false; END IF;
 -- Fresh wall clock AFTER all lock waits, not transaction-start time.
 t:=pg_catalog.clock_timestamp();
 IF c.expires_at<=t OR k.environment<>'production' OR k.assertion_counter>=p_counter THEN RETURN false; END IF;
 UPDATE subscription_ops.apple_app_attest_keys SET assertion_counter=p_counter,last_seen_at=t
 WHERE key_hash=c.key_hash AND environment='production' AND assertion_counter<p_counter;
 GET DIAGNOSTICS n=ROW_COUNT;
 IF n<>1 THEN RAISE EXCEPTION 'labels_auth_atomicity_failure'; END IF;
 UPDATE labels_auth.challenges SET consumed_at=t WHERE id=p_id AND consumed_at IS NULL;
 GET DIAGNOSTICS n=ROW_COUNT;
 -- Raising rolls back BOTH mutations. Never RETURN false after mutation.
 IF n<>1 THEN RAISE EXCEPTION 'labels_auth_atomicity_failure'; END IF;
 RETURN true;
END $$;
REVOKE ALL ON FUNCTION labels_auth.issue_challenge(uuid,text,text,text),labels_auth.read_challenge(uuid),
 labels_auth.consume_challenge(uuid,text,text,bigint) FROM PUBLIC,anon,authenticated,service_role;
GRANT USAGE ON SCHEMA labels_auth TO labels_auth_verifier;
GRANT EXECUTE ON FUNCTION labels_auth.issue_challenge(uuid,text,text,text),labels_auth.read_challenge(uuid),
 labels_auth.consume_challenge(uuid,text,text,bigint) TO labels_auth_verifier;
COMMIT;
